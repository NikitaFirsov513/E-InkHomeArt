#pragma once

#include <stdint.h>
#include "hal/gpio_types.h"
#include "sdkconfig.h"

#if !CONFIG_IDF_TARGET_ESP32S3
#error "E-InkHomeArt board configuration requires ESP32-S3"
#endif

/* ESP32-S3 GPIO numbers, NOT module pad or connector pin numbers. */
#define BOARD_PIN_EPD_MOSI       GPIO_NUM_45
#define BOARD_PIN_EPD_SCLK       GPIO_NUM_48
#define BOARD_PIN_EPD_CS         GPIO_NUM_47
#define BOARD_PIN_EPD_DC         GPIO_NUM_21
#define BOARD_PIN_EPD_RESET      GPIO_NUM_14
#define BOARD_PIN_EPD_BUSY       GPIO_NUM_13

#define BOARD_PIN_I2C_SDA        GPIO_NUM_10
#define BOARD_PIN_I2C_SCL        GPIO_NUM_11
#define BOARD_PIN_TOUCH_INT      GPIO_NUM_9
#define BOARD_PIN_TOUCH_RESET    GPIO_NUM_12
#define BOARD_PIN_LIS_INT        GPIO_NUM_39

#define BOARD_PIN_BATTERY_ADC    GPIO_NUM_1
#define BOARD_PIN_USB_CC1_ADC    GPIO_NUM_8
#define BOARD_PIN_USB_CC2_ADC    GPIO_NUM_3
#define BOARD_PIN_POWER_BUTTON   GPIO_NUM_2
#define BOARD_PIN_BOOT_BUTTON    GPIO_NUM_0
#define BOARD_PIN_STATUS_LED     GPIO_NUM_6
/* Output to Q2 gate; NOT an input reporting USB attachment. */
#define BOARD_PIN_ETA_USB_DET     GPIO_NUM_18

/* Owned by USB Serial/JTAG and optional debug UART, never generic GPIO init. */
#define BOARD_PIN_USB_DM         GPIO_NUM_19
#define BOARD_PIN_USB_DP         GPIO_NUM_20
#define BOARD_PIN_DEBUG_UART_RX  GPIO_NUM_44
#define BOARD_PIN_DEBUG_UART_TX  GPIO_NUM_43

#define BOARD_GPIO_BIT(pin) (UINT64_C(1) << (pin))

#define BOARD_GPIO_OUTPUT_MASK (BOARD_GPIO_BIT(BOARD_PIN_EPD_CS) | \
    BOARD_GPIO_BIT(BOARD_PIN_EPD_DC) | BOARD_GPIO_BIT(BOARD_PIN_EPD_RESET) | \
    BOARD_GPIO_BIT(BOARD_PIN_TOUCH_RESET) | BOARD_GPIO_BIT(BOARD_PIN_STATUS_LED) | \
    BOARD_GPIO_BIT(BOARD_PIN_ETA_USB_DET))

#define BOARD_GPIO_INPUT_MASK (BOARD_GPIO_BIT(BOARD_PIN_EPD_BUSY) | \
    BOARD_GPIO_BIT(BOARD_PIN_TOUCH_INT) | BOARD_GPIO_BIT(BOARD_PIN_LIS_INT) | \
    BOARD_GPIO_BIT(BOARD_PIN_POWER_BUTTON) | BOARD_GPIO_BIT(BOARD_PIN_BOOT_BUTTON))

#define BOARD_GPIO_SPI_MASK (BOARD_GPIO_BIT(BOARD_PIN_EPD_MOSI) | \
    BOARD_GPIO_BIT(BOARD_PIN_EPD_SCLK))
#define BOARD_GPIO_I2C_MASK (BOARD_GPIO_BIT(BOARD_PIN_I2C_SDA) | \
    BOARD_GPIO_BIT(BOARD_PIN_I2C_SCL))
#define BOARD_GPIO_ADC_MASK (BOARD_GPIO_BIT(BOARD_PIN_BATTERY_ADC) | \
    BOARD_GPIO_BIT(BOARD_PIN_USB_CC1_ADC) | BOARD_GPIO_BIT(BOARD_PIN_USB_CC2_ADC))
#define BOARD_GPIO_USB_MASK (BOARD_GPIO_BIT(BOARD_PIN_USB_DM) | \
    BOARD_GPIO_BIT(BOARD_PIN_USB_DP))
#define BOARD_GPIO_UART_MASK (BOARD_GPIO_BIT(BOARD_PIN_DEBUG_UART_RX) | \
    BOARD_GPIO_BIT(BOARD_PIN_DEBUG_UART_TX))

#define BOARD_GPIO_USED_MASK (BOARD_GPIO_OUTPUT_MASK | BOARD_GPIO_INPUT_MASK | \
    BOARD_GPIO_SPI_MASK | BOARD_GPIO_I2C_MASK | BOARD_GPIO_ADC_MASK | \
    BOARD_GPIO_USB_MASK | BOARD_GPIO_UART_MASK)

/* SoC memory interface, including GPIO35..37 used by N16R8 Octal PSRAM. */
#define BOARD_GPIO_MEMORY_MASK (UINT64_C(0xFFF) << 26)
#define BOARD_GPIO_STRAPPING_MASK (BOARD_GPIO_BIT(GPIO_NUM_0) | \
    BOARD_GPIO_BIT(GPIO_NUM_3) | BOARD_GPIO_BIT(GPIO_NUM_45) | \
    BOARD_GPIO_BIT(GPIO_NUM_46))

/* Unconnected on this PCB; do not configure automatically. */
#define BOARD_GPIO_UNUSED_MASK (BOARD_GPIO_BIT(GPIO_NUM_4) | \
    BOARD_GPIO_BIT(GPIO_NUM_5) | BOARD_GPIO_BIT(GPIO_NUM_7) | \
    BOARD_GPIO_BIT(GPIO_NUM_15) | BOARD_GPIO_BIT(GPIO_NUM_16) | \
    BOARD_GPIO_BIT(GPIO_NUM_17) | BOARD_GPIO_BIT(GPIO_NUM_38) | \
    BOARD_GPIO_BIT(GPIO_NUM_40) | BOARD_GPIO_BIT(GPIO_NUM_41) | \
    BOARD_GPIO_BIT(GPIO_NUM_42) | BOARD_GPIO_BIT(GPIO_NUM_46))
