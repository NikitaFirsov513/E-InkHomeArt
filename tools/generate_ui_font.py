"""Generate offline firmware bitmap glyphs from the pinned OFL Noto Sans source.

Needs Pillow, only for regeneration. Firmware builds use the committed C file.
python tools/generate_ui_font.py --font build/references/NotoSans.ttf
"""
import argparse
import hashlib
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
SHA='bfb7bb691513f12e734dc346c03a03f784912432d7e3fa8e56efcf906fe86b3d'
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font',type=Path,required=True)
args=parser.parse_args()
assert hashlib.sha256(args.font.read_bytes()).hexdigest()==SHA,'Use the pinned Noto Sans source'
codes=sorted(set(range(32,127))|set(range(0x410,0x450))|{0x401,0x451,0xb0,0xb7})
lines=['/* Generated by tools/generate_ui_font.py. Home Art Sans Bitmap.',
       ' * Derived from Noto Sans, SIL OFL 1.1; see vendor/OFL.txt and UPSTREAM.md. */',
       '#include "home_ui_font.h"']
total=0
for name,size,weight in [("18",18,400),("20",20,400),("20_bold",20,600),("28",28,600),("48",48,600)]:
    font=ImageFont.truetype(str(args.font),size)
    font.set_variation_by_axes([weight,100])
    ascent,descent=font.getmetrics();height=ascent+descent
    data=[];glyphs=[]
    font_codes=codes if size!=48 else sorted(set(map(ord,"0123456789.,-+% °CKeE?")))
    for code in font_codes:
        char=chr(code)
        width=max(1,math.ceil(font.getlength(char)))
        image=Image.new('L',(width,height),0)
        ImageDraw.Draw(image).text((0,ascent),char,font=font,anchor='ls',fill=255)
        offset=len(data)
        for y in range(height):
            for x0 in range(0,width,8):
                value=0
                for bit in range(8):
                    if x0+bit<width and image.getpixel((x0+bit,y))>=128:value|=128>>bit
                data.append(value)
        glyphs.append(f'    {{{code},{offset},{width}}},')
    lines.append(f'static const uint8_t bits_{name}[] = {{')
    lines.extend('    '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24))
    lines+=['};',f'static const home_font_glyph_t glyphs_{name}[] = {{',*glyphs,'};',
            f'const home_font_t home_font_{name} = {{{height},{len(font_codes)},glyphs_{name},bits_{name}}};']
    total+=len(data)
(ROOT/'components/home_ui/home_ui_font.c').write_bytes(('\n'.join(lines)+'\n').encode())
print(f'Generated {len(codes)} glyphs at 18/20/20-semibold/28/48 px, {total} bitmap bytes.')
